// Detect the movement category from exercise name
function detectCategory(name = '') {
  const n = name.toLowerCase()
  if (/squat|leg press|lunge|step.?up/.test(n)) return 'compound-squat'
  if (/deadlift|hinge|good.?morning|rdl|romanian/.test(n)) return 'compound-hinge'
  if (/bench|press|push|dip|thruster/.test(n)) return 'compound-push'
  if (/row|pull|chin|face pull|shrug/.test(n)) return 'compound-pull'
  if (/curl|extension|raise|fly|flye|kickback|pushdown/.test(n)) return 'isolation'
  if (/burpee|thruster|clean|snatch|jerk|swing|box|wall ball|wod|amrap|emom/.test(n)) return 'metcon'
  return 'default'
}

// Main lookup function - returns cues object with fallback
export function cuesForExercise(exerciseName, exerciseId) {
  // Try direct ID match first
  if (exerciseId && CUES_DB[exerciseId]) return { ...CUES_DB[exerciseId], _matched: 'id' }

  const nLower = (exerciseName || '').toLowerCase()

  // Try name-based fuzzy match
  for (const [key, entry] of Object.entries(CUES_DB)) {
    const matchNames = [entry.name, entry.nameHe, ...(entry.aliases || [])].filter(Boolean)
    if (matchNames.some(n => nLower.includes(n.toLowerCase()) || n.toLowerCase().includes(nLower))) {
      return { ...entry, _matched: 'name' }
    }
  }

  // Fallback by category
  const cat = detectCategory(exerciseName)
  return {
    id: 'fallback',
    name: exerciseName || 'Exercise',
    nameHe: exerciseName || 'תרגיל',
    target: 'שריר יעד לפי סוג התרגיל',
    ytId: null, ytBy: null,
    ...FALLBACK_TEMPLATES[cat],
    easier: 'הפחת משקל או השתמש בגרסה מותאמת',
    harder: 'הוסף משקל, טווח, או מורכבות',
    _matched: 'fallback', _category: cat,
  }
}
