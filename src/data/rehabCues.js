// Fuzzy lookup - returns cues for an exercise name, or null if no match
export function rehabCuesFor(exerciseName) {
  if (!exerciseName) return null
  const nLower = exerciseName.toLowerCase().trim()

  // Direct hit
  if (REHAB_CUES[exerciseName]) return REHAB_CUES[exerciseName]
  if (REHAB_CUES[nLower]) return REHAB_CUES[nLower]

  // Substring match
  for (const [key, entry] of Object.entries(REHAB_CUES)) {
    if (nLower.includes(key.toLowerCase()) || key.toLowerCase().includes(nLower)) {
      return entry
    }
  }

  return null
}
