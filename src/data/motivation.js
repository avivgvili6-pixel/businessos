export function quoteOfDay(dateStr = null) {
  const d = dateStr || new Date().toISOString().slice(0, 10)
  let hash = 0
  for (let i = 0; i < d.length; i++) hash = (hash * 31 + d.charCodeAt(i)) | 0
  return DAILY_QUOTES[Math.abs(hash) % DAILY_QUOTES.length]
}

